"""Build skills/design-md-reference/INDEX.md from the vendored awesome-design-md README."""
import re, sys, pathlib

root = pathlib.Path(sys.argv[1])
lock = [l.split("\t") for l in (root / "vendor.lock").read_text().splitlines()
        if l and not l.startswith("#")]
repo, sha = next((r[1], r[2]) for r in lock if r[0] == "awesome-design-md")
skill = root / "skills/design-md-reference"
readme = (skill / "upstream-README.md").read_text()

body = readme.split("## Collection", 1)[1].split("\n## ", 1)[0]
out = [
    "# DESIGN.md index",
    "",
    f"Generated by `scripts/sync-vendor.sh` from `{repo}@{sha[:12]}`. Do not edit by hand.",
    "",
    "Fetch one with:",
    "",
    f"`https://raw.githubusercontent.com/{repo}/{sha}/design-md/<slug>/DESIGN.md`",
    "",
]
count = 0
seen = set()
for line in body.splitlines():
    if line.startswith("### "):
        out += ["", line, "", "| slug | site | character |", "| --- | --- | --- |"]
        continue
    m = re.match(r"- \[\*\*(.+?)\*\*\]\(https://getdesign\.md/([^/]+)/design-md\)\s*-\s*(.*)", line)
    if m:
        name, slug, desc = m.groups()
        out.append(f"| `{slug}` | {name} | {desc.strip()} |")
        seen.add(slug)
        count += 1
slugs_file = skill / "upstream-slugs.txt"
extra = [s for s in slugs_file.read_text().split() if s not in seen] if slugs_file.exists() else []
if extra:
    out += ["", "### Uncategorised (in the repo, not in the upstream README)", "",
            "| slug | site | character |", "| --- | --- | --- |"]
    out += [f"| `{s}` | {s} | — |" for s in extra]
    count += len(extra)
(skill / "INDEX.md").write_text("\n".join(out) + "\n")
print(f"design-md index: {count} sites")
